def write_templates(out_dir):
    root = Path(out_dir)
    configs = root / "configs"
    configs.mkdir(parents=True, exist_ok=True)
    plans = [make_config(mesh_level=level) for level in MESH_LEVELS]
    plans += [make_config(split_policy="imposed_equal_split_baseline"),
              make_config(model="kOmegaSST", inlet_intensity_fraction=.01),
              make_config(model="kOmegaSST", inlet_intensity_fraction=.05),
              make_config(mode="static_pressure_difference"),
              make_config(mode="recording_total0_staticplus18")]
    records = []
    for config in plans:
        validation = validate_config(config)
        if not validation["valid"]:
            raise ContractError("generated invalid template: " + repr(validation["errors"]))
        path = configs / (config["config_id"] + ".json")
        path.write_text(json.dumps(config, ensure_ascii=False, indent=2, allow_nan=False)+"\n", encoding="utf-8")
        records.append({"config_id": config["config_id"], "file": str(path), "validation": validation})
    manifest = {"schema": "nasal_cfd_config_catalog/v1", "config_schema": CONFIG_SCHEMA,
                "result_schema": RESULT_SCHEMA, "status": "templates_only_no_patient_cfd_results",
                "configs": records}
    (root/"config_catalog.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2, allow_nan=False)+"\n", encoding="utf-8")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-templates", action="store_true")
    parser.add_argument("--out-dir", default=str(ROOT/"work"/"07_cfd_pipeline"))
    parser.add_argument("--validate-config", type=Path)
    parser.add_argument("--validate-result", type=Path)
    parser.add_argument("--require-execution-ready", action="store_true")
    args = parser.parse_args()
    reports = []
    if args.write_templates:
        manifest = write_templates(args.out_dir)
        reports.append({"written_config_count": len(manifest["configs"]), "patient_solver_runs": 0})
    config = json.loads(args.validate_config.read_text(encoding="utf-8")) if args.validate_config else None
    if config is not None:
        reports.append(validate_config(config, args.require_execution_ready))
    if args.validate_result:
        reports.append(validate_result(json.loads(args.validate_result.read_text(encoding="utf-8")), config=config))
    if not reports:
        parser.error("choose --write-templates, --validate-config, or --validate-result")
    print(json.dumps(reports, ensure_ascii=False, indent=2, allow_nan=False))
    return 1 if any(r.get("valid") is False for r in reports) else 0


if __name__ == "__main__":
    raise SystemExit(main())
