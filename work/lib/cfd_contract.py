"""CFD configuration/result contracts and explicit field conversions.

Validation checks metadata and numerical consistency, not a clinician's identity,
the authenticity of an external file, anatomical accuracy, or clinical efficacy.
No solver is run and no patient flow field is generated by this module.
"""
import argparse
import json
import math
from pathlib import Path
import re

import numpy as np

CONFIG_SCHEMA = "nasal_cfd_config/v1"
RESULT_SCHEMA = "nasal_cfd_result/v1"
ROOT = Path(__file__).resolve().parents[2]
RESULT_TYPES = {"patient_preview", "analytic_reference", "cfd_result"}
MODELS = {"laminar", "kOmegaSST"}
BOUNDARIES = {"nostril_L", "nostril_R", "nasopharynx_outlet"}
TI_DEFINITION = "sqrt(2*k/3)/magnitude(U)"
MESH_LEVELS = {"coarse": (0.6, 0.30), "medium": (0.4, 0.25), "fine": (0.275, 0.20)}


class ContractError(ValueError):
    """A configuration or result violates an explicit project contract."""


def _number(value, positive=False, nonnegative=False):
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, float, np.number)):
        return False
    return bool(np.isfinite(value) and (not positive or value > 0)
                and (not nonnegative or value >= 0))


def _text(value):
    return isinstance(value, str) and bool(value.strip())


def _report(errors, warnings, execution_allowed=False):
    return {"valid": not errors, "errors": errors, "warnings": warnings,
            "execution_allowed": bool(execution_allowed and not errors),
            "validation_scope": "contract_metadata_and_inline_values_only"}


def flow_lpm_to_m3_s(value):
    if not _number(value, positive=True):
        raise ContractError("flow in L/min must be finite and positive")
    return float(value) * 1e-3 / 60.


def inlet_mean_speed_m_s(flow_m3_s, area_mm2):
    if not _number(flow_m3_s, positive=True) or not _number(area_mm2, positive=True):
        raise ContractError("flow_m3_s and area_mm2 must be finite and positive")
    return float(flow_m3_s) * 1e6 / float(area_mm2)


def pressure_to_pa(values, source_unit, rho_kg_m3=None, source_field="p"):
    """Convert explicit Pa or m2/s2 values; preserve pressure reference and sign.

    p_rgh is deliberately rejected: density scaling alone cannot reconstruct
    hydrostatic pressure. Supply already reconstructed p instead.
    """
    if source_field == "p_rgh":
        raise ContractError("p_rgh requires hydrostatic reconstruction before pressure_to_pa")
    array = np.asarray(values, dtype=float)
    if not np.isfinite(array).all():
        raise ContractError("pressure values must be finite")
    if source_unit == "Pa":
        converted = array.copy()
    elif source_unit == "m2/s2":
        if not _number(rho_kg_m3, positive=True):
            raise ContractError("kinematic pressure conversion requires positive rho_kg_m3")
        converted = array * float(rho_kg_m3)
    else:
        raise ContractError("source_unit must explicitly be Pa or m2/s2")
    return float(converted) if converted.ndim == 0 else converted.tolist()


def compute_turbulence_intensity(velocity_m_s, k_m2_s2=None, model="laminar",
                                 low_speed_threshold_m_s=None):
    """Return a JSON-safe dimensionless TI field, or None for laminar.

    k is modeled turbulent kinetic energy in m2/s2, velocity has shape (N,3).
    SST values at |U| <= the explicit threshold are null, never a clipped ratio.
    The returned fraction is multiplied by 100 only for a percent display.
    """
    if model == "laminar":
        if k_m2_s2 is not None:
            raise ContractError("laminar results must not carry modeled turbulence kinetic energy")
        return None
    if model != "kOmegaSST":
        raise ContractError("unsupported turbulence model")
    if not _number(low_speed_threshold_m_s, positive=True):
        raise ContractError("SST TI requires an explicit positive low_speed_threshold_m_s")
    velocity = np.asarray(velocity_m_s, dtype=float)
    k = np.asarray(k_m2_s2, dtype=float)
    if velocity.ndim != 2 or velocity.shape[1] != 3 or k.shape != (len(velocity),):
        raise ContractError("SST velocity must be (N,3) and k must be (N,)")
    if not np.isfinite(velocity).all() or not np.isfinite(k).all() or np.any(k < 0):
        raise ContractError("SST U and k must be finite and k must be nonnegative")
    speed = np.linalg.norm(velocity, axis=1)
    valid = speed > float(low_speed_threshold_m_s)
    intensity = np.zeros(len(k), dtype=float)
    intensity[valid] = np.sqrt(2.*k[valid]/3.) / speed[valid]
    return {"unit": "1", "display_unit": "%", "association": "point",
            "definition": TI_DEFINITION, "model": "kOmegaSST",
            "low_speed_threshold_m_s": float(low_speed_threshold_m_s),
            "values": [float(v) if ok else None for v, ok in zip(intensity, valid)],
            "valid_mask": valid.tolist(), "masked_count": int((~valid).sum()),
            "mask_reason": "magnitude(U) <= low_speed_threshold_m_s",
            "interpretation": "isotropic convention from modeled k; not a measurement"}


def _patient_geometry_issues(geometry):
    issues = []
    if not isinstance(geometry, dict) or geometry.get("kind") != "patient":
        return ["patient geometry metadata is required"]
    for name in ("case_id", "source_file"):
        if not _text(geometry.get(name)):
            issues.append("geometry." + name + " is required for patient execution")
    digest = geometry.get("sha256")
    if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-fA-F]{64}", digest):
        issues.append("geometry.sha256 must bind the reviewed geometry")
    review = geometry.get("review", {})
    if not isinstance(review, dict):
        return issues + ["geometry.review must be an object"]
    if review.get("status") != "confirmed" or review.get("method") != "human":
        issues.append("patient geometry requires human confirmed review")
    for name in ("reviewer", "reviewed_at", "record_file"):
        if not _text(review.get(name)):
            issues.append("geometry.review." + name + " is required")
    if review.get("reviewed_geometry_sha256") != digest or not digest:
        issues.append("review must reference the same geometry sha256")
    confirmed = review.get("confirmed_boundaries", [])
    if not isinstance(confirmed, list) or not BOUNDARIES.issubset(set(x for x in confirmed if isinstance(x, str))):
        issues.append("both nostrils and nasopharynx outlet must be confirmed")
    if review.get("oral_exclusion_confirmed") is not True:
        issues.append("oral exclusion must be confirmed")
    if review.get("sinus_boundary_policy_confirmed") is not True:
        issues.append("sinus boundary policy must be confirmed")
    return issues


def _check_pressure_boundary(boundary, name, errors):
    if not isinstance(boundary, dict):
        errors.append(name + " must be an explicit pressure object")
        return
    if boundary.get("quantity") not in {"static", "total"}:
        errors.append(name + ".quantity must be static or total")
    if boundary.get("unit") != "Pa" or boundary.get("reference") != "gauge":
        errors.append(name + " must be in Pa with an explicit gauge reference")
    if not _number(boundary.get("value")):
        errors.append(name + ".value must be finite")


def validate_config(config, require_execution_ready=False):
    """Validate a template, optionally requiring ready patient geometry metadata.

    A valid engineering template can still have execution_allowed=False.
    The caller must verify review/file authenticity and implement the solver adapter.
    """
    errors, warnings = [], []
    if not isinstance(config, dict):
        return _report(["config must be an object"], [])
    if config.get("schema") != CONFIG_SCHEMA:
        errors.append("schema must be " + CONFIG_SCHEMA)
    if not _text(config.get("config_id")):
        errors.append("config_id is required")
    physics = config.get("physics", {})
    if not isinstance(physics, dict):
        physics = {}
    for name in ("rho_kg_m3", "mu_Pa_s"):
        if not _number(physics.get(name), positive=True):
            errors.append("physics." + name + " must be positive in stated SI units")
    if physics.get("flow_regime") != "incompressible" or physics.get("time_mode") != "steady":
        errors.append("v1 baseline contract is steady and incompressible")
    model = physics.get("turbulence_model")
    if model not in MODELS:
        errors.append("physics.turbulence_model must be laminar or kOmegaSST")
    turbulence = config.get("turbulence", {})
    if not isinstance(turbulence, dict):
        turbulence = {}
    if model == "laminar":
        for name in ("inlet_intensity_fraction", "length_scale_Dh_fraction", "low_speed_threshold_m_s"):
            if turbulence.get(name) is not None:
                errors.append("laminar turbulence." + name + " must be null")
        if turbulence.get("report_status") != "not_applicable":
            errors.append("laminar report_status must be not_applicable")
    elif model == "kOmegaSST":
        intensity = turbulence.get("inlet_intensity_fraction")
        if not _number(intensity, positive=True) or intensity >= 1:
            errors.append("SST inlet_intensity_fraction must be a fraction between 0 and 1")
        for name in ("length_scale_Dh_fraction", "low_speed_threshold_m_s"):
            if not _number(turbulence.get(name), positive=True):
                errors.append("SST turbulence." + name + " must be explicit and positive")
        if turbulence.get("definition") != TI_DEFINITION:
            errors.append("SST turbulence definition is missing or unsupported")
    bc = config.get("boundary_conditions", {})
    if not isinstance(bc, dict):
        bc = {}
    allowed_bc = {"mode", "total_inspiratory_flow_m3_s", "flow_split", "nostril_pressure",
                  "nasopharynx_pressure", "static_pressure_difference_Pa", "direction_policy", "walls"}
    if set(bc) - allowed_bc:
        errors.append("unknown boundary keys may hide extra constraints: " + ", ".join(sorted(set(bc)-allowed_bc)))
    mode = bc.get("mode")
    flow = bc.get("total_inspiratory_flow_m3_s")
    inlet = bc.get("nostril_pressure")
    outlet = bc.get("nasopharynx_pressure")
    _check_pressure_boundary(outlet, "nasopharynx_pressure", errors)
    if isinstance(outlet, dict) and outlet.get("quantity") != "static":
        errors.append("nasopharynx boundary must use static pressure")
    if mode == "total_flow":
        if not _number(flow, positive=True):
            errors.append("total_flow requires positive total_inspiratory_flow_m3_s")
        if inlet is not None or bc.get("static_pressure_difference_Pa") is not None:
            errors.append("fixed total flow must not also prescribe nostril pressure or a two-end pressure difference")
        split = bc.get("flow_split", {})
        if not isinstance(split, dict):
            split = {}
        if split.get("policy") == "solver_determined":
            if split.get("left_fraction") is not None or split.get("right_fraction") is not None:
                errors.append("solver_determined split must not prescribe per-side fractions")
            warnings.append("total flow is an outer pressure-feedback target; no generic joint-flow OpenFOAM boundary is assumed")
        elif split.get("policy") == "imposed_equal_split_baseline":
            if split.get("left_fraction") != 0.5 or split.get("right_fraction") != 0.5:
                errors.append("equal-split baseline requires 0.5 for each side")
            if split.get("interpretation") != "imposed_baseline_not_patient_split":
                errors.append("equal split must not be labeled as patient flow distribution")
        else:
            errors.append("total_flow requires an explicit supported split policy")
    elif mode in {"static_pressure_difference", "recording_total0_staticplus18"}:
        if flow is not None or bc.get("flow_split") is not None:
            errors.append("pressure-driven cases cannot simultaneously prescribe total flow or bilateral split")
        _check_pressure_boundary(inlet, "nostril_pressure", errors)
        if mode == "static_pressure_difference":
            delta = bc.get("static_pressure_difference_Pa")
            if not _number(delta, positive=True):
                errors.append("static pressure difference must be positive for the declared inspiration direction")
            if isinstance(inlet, dict) and inlet.get("quantity") != "static":
                errors.append("static-to-static pressure difference cannot use total inlet pressure")
            if isinstance(inlet, dict) and isinstance(outlet, dict) and _number(inlet.get("value")) and _number(outlet.get("value")) and _number(delta):
                if not math.isclose(inlet["value"]-outlet["value"], delta, abs_tol=1e-9, rel_tol=0):
                    errors.append("static delta must equal nostril static pressure minus nasopharynx static pressure")
        else:
            if not isinstance(inlet, dict) or inlet.get("quantity") != "total" or inlet.get("value") != 0:
                errors.append("recording reproduction requires nostril total pressure 0 Pa")
            if not isinstance(outlet, dict) or outlet.get("value") != 18:
                errors.append("recording reproduction requires nasopharynx static gauge pressure +18 Pa")
            if bc.get("static_pressure_difference_Pa") is not None:
                errors.append("recording total/static settings must not be labeled static pressure drop 18 Pa")
            if bc.get("direction_policy") != "measure_signed_boundary_flux_before_interpretation":
                errors.append("recording reproduction requires signed-flow direction verification")
    else:
        errors.append("unsupported boundary_conditions.mode")
    if bc.get("walls") != "rigid_no_slip":
        errors.append("v1 baseline walls must be rigid_no_slip")
    mesh = config.get("mesh", {})
    if not isinstance(mesh, dict):
        mesh = {}
    for name in ("bulk_target_mm", "local_initial_target_mm"):
        if not _number(mesh.get(name), positive=True):
            errors.append("mesh." + name + " must be positive")
    if mesh.get("minimum_cells_across_gap") != 6:
        errors.append("mesh must retain the explicit six-cell gap requirement")
    if mesh.get("local_resolution_rule") != "h <= min(local_initial_target_mm, measured_gap_mm/6)":
        errors.append("mesh must not treat the initial local target as sufficient for every gap")
    geometry = config.get("geometry", {})
    if not isinstance(geometry, dict):
        geometry = {}
    if geometry.get("units") not in {"mm", "m"}:
        errors.append("geometry.units must be explicit mm or m")
    expected_scale = {"mm": 0.001, "m": 1.0}.get(geometry.get("units"))
    if geometry.get("solver_units") != "m" or geometry.get("scale_to_m") != expected_scale:
        errors.append("geometry must carry the correct single conversion to solver metres")
    if geometry.get("coordinate_system") not in {"LPS", "RAS", "idealized_cartesian"}:
        errors.append("geometry.coordinate_system must be explicit")
    readiness = []
    if geometry.get("kind") == "patient":
        readiness += _patient_geometry_issues(geometry)
    elif geometry.get("kind") == "idealized":
        if not _text(geometry.get("source_file")):
            readiness.append("idealized source geometry is missing")
    else:
        errors.append("geometry.kind must be patient or idealized")
    adapter = config.get("solver_adapter", {})
    if not isinstance(adapter, dict) or adapter.get("status") != "implemented_and_verified":
        readiness.append("solver adapter has not been implemented and verified for these boundary conditions")
    if mode == "total_flow" and isinstance(bc.get("flow_split"), dict) and bc["flow_split"].get("policy") == "solver_determined":
        if not isinstance(adapter, dict) or adapter.get("desired_strategy") != "common_inlet_pressure_feedback":
            errors.append("solver-determined split requires the explicit common_inlet_pressure_feedback strategy")
        elif adapter.get("flow_target_role") != "outer_iteration_objective_not_simultaneous_PDE_flow_boundary":
            errors.append("pressure-feedback flow target must remain an outer objective")
    if require_execution_ready:
        errors.extend(readiness)
    else:
        warnings.extend(readiness)
    return _report(errors, warnings, not readiness)


def _validate_field(field, name, unit, components, errors):
    if not isinstance(field, dict):
        errors.append(name + " must be a field object")
        return None
    if field.get("unit") != unit:
        errors.append(name + ".unit must be " + unit)
    if field.get("association") not in {"point", "cell"}:
        errors.append(name + ".association must be point or cell")
    inline = "values" in field and field["values"] is not None
    external = _text(field.get("data_file"))
    if inline == external:
        errors.append(name + " requires exactly one of inline values or data_file")
        return None
    if not inline:
        return None
    try:
        array = np.asarray(field["values"], dtype=float)
        expected_shape = array.ndim == 1 if components == 1 else array.ndim == 2 and array.shape[1] == components
        if not expected_shape or not len(array) or not np.isfinite(array).all():
            errors.append(name + " has wrong shape, empty data, or nonfinite values")
            return None
        return array
    except (TypeError, ValueError):
        errors.append(name + " values must be numeric")
        return None


def validate_result(result, config=None):
    """Validate provenance, geometry gate and all inline physical field values.

    External data_file values require independent file/array validation before
    publication; this function does not claim to inspect them.
    """
    errors, warnings = [], []
    if not isinstance(result, dict):
        return _report(["result must be an object"], [])
    if result.get("schema") != RESULT_SCHEMA:
        errors.append("schema must be " + RESULT_SCHEMA)
    result_type = result.get("type")
    if result_type not in RESULT_TYPES:
        errors.append("unsupported result type")
    geometry = result.get("geometry", {})
    if not isinstance(geometry, dict):
        geometry = {}
    fields = result.get("fields", {})
    if not isinstance(fields, dict) or set(fields) != {"velocity", "pressure", "turbulence_intensity"}:
        errors.append("fields must explicitly contain velocity, pressure, turbulence_intensity")
        fields = fields if isinstance(fields, dict) else {}
    provenance = result.get("provenance", {})
    if not isinstance(provenance, dict):
        provenance = {}
    if result_type == "patient_preview":
        if geometry.get("kind") != "patient" or not _text(geometry.get("case_id")):
            errors.append("patient_preview requires a patient geometry case_id")
        if any(fields.get(name) is not None for name in ("velocity", "pressure", "turbulence_intensity")):
            errors.append("patient_preview must not contain computed flow fields")
        if provenance.get("method") != "segmentation_surface_preview":
            errors.append("patient_preview provenance must be segmentation_surface_preview")
        if result.get("clinical_validation") != "not_validated":
            errors.append("patient_preview clinical_validation must be not_validated")
        return _report(errors, warnings)
    if result_type == "analytic_reference":
        if geometry.get("kind") != "idealized" or geometry.get("case_id") is not None:
            errors.append("analytic_reference must be idealized and cannot name a patient case")
        if provenance.get("method") != "analytic_solution" or not _text(provenance.get("equation")):
            errors.append("analytic_reference needs an explicit analytical equation")
        if result.get("clinical_validation") != "not_validated":
            errors.append("analytic_reference is not clinically validated")
    elif result_type == "cfd_result":
        if geometry.get("kind") == "patient":
            errors += _patient_geometry_issues(geometry)
        elif geometry.get("kind") != "idealized":
            errors.append("cfd_result geometry.kind must be patient or idealized")
        if provenance.get("method") != "cfd_solver":
            errors.append("cfd_result requires cfd_solver provenance")
        for key in ("solver_name", "solver_version", "run_id", "run_log", "config_id"):
            if not _text(provenance.get(key)):
                errors.append("cfd_result provenance." + key + " is required")
        diagnostics = result.get("diagnostics", {})
        if not isinstance(diagnostics, dict):
            diagnostics = {}
        for key in ("mass_imbalance_fraction", "monitor_relative_change", "residual_max"):
            if not _number(diagnostics.get(key), nonnegative=True):
                errors.append("cfd_result diagnostics." + key + " must contain the measured nonnegative value")
        if result.get("numerical_validation") not in {"unchecked", "failed", "passed_engineering_screen"}:
            errors.append("cfd_result must declare numerical_validation")
        if result.get("clinical_validation") != "not_validated":
            errors.append("CFD completion does not establish clinical validation")
        if result.get("numerical_validation") == "passed_engineering_screen":
            screen = config.get("engineering_screen", {}) if isinstance(config, dict) else {}
            for measured, setting, default in [("mass_imbalance_fraction", "maximum_mass_imbalance_fraction", .005),
                                                ("monitor_relative_change", "maximum_monitor_relative_change", .005),
                                                ("residual_max", "target_residual_max", 1e-5)]:
                limit = screen.get(setting, default)
                if not _number(limit, positive=True) or (_number(diagnostics.get(measured)) and diagnostics[measured] > limit):
                    errors.append("passed_engineering_screen contradicts " + measured)
    physics = result.get("physics", {})
    if not isinstance(physics, dict):
        physics = {}
    model = physics.get("turbulence_model")
    if model not in MODELS:
        errors.append("result physics.turbulence_model must be explicit")
    for name in ("rho_kg_m3", "mu_Pa_s"):
        if not _number(physics.get(name), positive=True):
            errors.append("result physics." + name + " must be positive")
    velocity = _validate_field(fields.get("velocity"), "velocity", "m/s", 3, errors)
    pressure = _validate_field(fields.get("pressure"), "pressure", "Pa", 1, errors)
    p = fields.get("pressure")
    if isinstance(p, dict):
        if p.get("quantity") not in {"static", "total"} or p.get("reference") != "gauge":
            errors.append("pressure must explicitly identify static/total and gauge reference")
        if p.get("source_unit") not in {"Pa", "m2/s2"}:
            errors.append("pressure.source_unit is required; OpenFOAM p must not be guessed")
        if p.get("source_field") == "p_rgh":
            errors.append("raw p_rgh requires hydrostatic reconstruction before publishing pressure")
        if p.get("source_unit") == "m2/s2":
            if not _number(p.get("rho_kg_m3"), positive=True) or p.get("conversion") != "p_Pa = rho_kg_m3 * p_kinematic":
                errors.append("kinematic pressure requires recorded positive density and explicit conversion")
            elif _number(physics.get("rho_kg_m3"), positive=True) and not math.isclose(p["rho_kg_m3"], physics["rho_kg_m3"], rel_tol=1e-12):
                errors.append("pressure conversion density differs from result fluid density")
    if velocity is not None and pressure is not None and isinstance(p, dict):
        if fields["velocity"].get("association") == p.get("association") and len(velocity) != len(pressure):
            errors.append("velocity and pressure lengths differ on the same association")
    ti = fields.get("turbulence_intensity")
    if model == "laminar":
        if ti is not None:
            errors.append("laminar turbulence_intensity must be null, never a field of zeros")
        if result.get("turbulence_intensity_status") != "not_applicable":
            errors.append("laminar turbulence_intensity_status must be not_applicable")
    elif model == "kOmegaSST":
        if not isinstance(ti, dict):
            errors.append("SST result requires an explicitly masked turbulence intensity field")
        else:
            if ti.get("unit") != "1" or ti.get("definition") != TI_DEFINITION or ti.get("model") != "kOmegaSST":
                errors.append("SST TI must use the declared dimensionless isotropic convention")
            threshold = ti.get("low_speed_threshold_m_s")
            if not _number(threshold, positive=True):
                errors.append("SST TI must record positive low_speed_threshold_m_s")
            values, valid = ti.get("values"), ti.get("valid_mask")
            if not isinstance(values, list) or not isinstance(valid, list) or len(values) != len(valid) or not values:
                errors.append("SST TI requires inline values and equal-length valid_mask")
            else:
                for value, keep in zip(values, valid):
                    if type(keep) is not bool or (keep and not _number(value, nonnegative=True)) or (not keep and value is not None):
                        errors.append("SST masked values must be null and valid values finite/nonnegative")
                        break
                if velocity is not None and ti.get("association") == fields["velocity"].get("association"):
                    if len(values) != len(velocity):
                        errors.append("SST TI and U lengths differ on the same association")
                    elif _number(threshold, positive=True):
                        expected = np.linalg.norm(velocity, axis=1) > threshold
                        if not np.array_equal(expected, np.asarray(valid)):
                            errors.append("SST TI mask disagrees with the recorded low-speed threshold")
    if config is not None:
        checked = validate_config(config)
        if not checked["valid"]:
            errors.append("linked configuration is invalid")
        if result_type == "cfd_result" and provenance.get("config_id") != config.get("config_id"):
            errors.append("result config_id does not match linked configuration")
        if model != config.get("physics", {}).get("turbulence_model"):
            errors.append("result turbulence model differs from linked configuration")
        for name in ("rho_kg_m3", "mu_Pa_s"):
            configured = config.get("physics", {}).get(name)
            if _number(configured) and _number(physics.get(name)) and not math.isclose(configured, physics[name], rel_tol=1e-12):
                errors.append("result physics." + name + " differs from linked configuration")
        if result_type == "cfd_result":
            execution_check = validate_config(config, require_execution_ready=True)
            if not execution_check["valid"]:
                errors.append("linked configuration was not execution-ready")
            if geometry.get("kind") == "patient" and geometry.get("sha256") != config.get("geometry", {}).get("sha256"):
                errors.append("result geometry hash differs from linked configuration")
        imposed = config.get("boundary_conditions", {}).get("flow_split") or {}
        if imposed.get("policy") == "imposed_equal_split_baseline" and result.get("flow_split_interpretation") != "imposed_baseline_not_patient_split":
            errors.append("equal-split run must retain imposed-baseline interpretation")
    if any(isinstance(f, dict) and _text(f.get("data_file")) for f in fields.values()):
        warnings.append("external field contents are not inspected; validate arrays before publication")
    return _report(errors, warnings)


def make_config(mode="total_flow", mesh_level="medium", model="laminar",
                inlet_intensity_fraction=None, split_policy="solver_determined"):
    if mesh_level not in MESH_LEVELS or model not in MODELS:
        raise ContractError("unsupported mesh level or model")
    bulk, local = MESH_LEVELS[mesh_level]
