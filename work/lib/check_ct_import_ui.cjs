// Actual upload -> CPU inference -> generated case review. Isolated QA case root.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const {chromium} = require('playwright');
const base = process.argv[2] || 'http://127.0.0.1:8770';
const input = process.argv[3] || 'C:/ts_work/p1/ct.nii.gz';
const qa = path.resolve(__dirname,'../07_cfd_pipeline/workspace/qa');
const hash = async p => crypto.createHash('sha256').update(await fs.readFile(p)).digest('hex');
(async () => {
  await fs.mkdir(qa,{recursive:true});
  const original = await hash(input);
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000}}), page = await context.newPage();
    page.setDefaultTimeout(20000);
    const errors=[];page.on('pageerror',err=>errors.push(err.message));
    await page.goto(base + '/workspace/index.html#import');
    await page.locator('#ct-file').setInputFiles(input);
    assert(await page.locator('#upload-start').isDisabled(),'HU confirmation required for NIfTI');
    await page.locator('#hu-confirmed').check();
    await page.locator('#upload-start').click();
    await page.locator('#run-title').filter({hasText:'u_'}).waitFor();
    const id = (await page.locator('#run-title').textContent()).match(/u_[0-9a-f]{16}/)[0];
    await page.waitForFunction(() => document.getElementById('pipeline-stages').querySelectorAll('[data-state=running]').length > 0,{},{timeout:60000});
    console.log(JSON.stringify({status:'real_cpu_pipeline_started',case:id}));
    await page.screenshot({path:path.join(qa,'ct-import-running.png')});
    await page.reload();
    await page.locator('#run-title').filter({hasText:id}).waitFor();
    await page.locator('#case-open-actions').waitFor({state:'visible',timeout:600000});
    assert(!(await page.locator('#case-error').isVisible()),'Real CT pipeline failed');
    await page.screenshot({path:path.join(qa,'ct-import-ready.png')});
    const state = await page.request.get(base+'/api/cases/'+id).then(r=>r.json());
    assert.equal(state.status,'awaiting_review');
    assert.equal(state.stages.import,'done');assert.equal(state.stages.segmentation,'done');assert.equal(state.stages.candidates,'done');
    assert.equal(state.patient_cfd_results,0);assert.equal(state.stages.solver,'pending');
    await page.locator('#open-case-geometry').click();
    const frame = page.frameLocator('#panel-geometry iframe:not([hidden])');
    await frame.locator('#scene-state').waitFor({state:'hidden',timeout:30000});
    assert.equal(await frame.locator('#layer-pressure').isDisabled(),true);
    await page.screenshot({path:path.join(qa,'ct-import-geometry.png')});
    await page.locator('[data-step=review]').click();
    const review = page.frameLocator('#panel-review iframe:not([hidden])');
    await review.locator('#cards .card').first().waitFor();
    await review.locator('#reviewer').fill('QA persistence test');
    await review.locator('#cards .card').first().locator('textarea').fill('QA draft only; no anatomy approval');
    await page.locator('#save-case-review').click();
    await page.locator('#active-case-state').filter({hasText:'审核已保存'}).waitFor();
    const saved = await page.request.get(base+'/api/cases/'+id).then(r=>r.json());
    assert.equal(saved.status,'awaiting_review','Pending decisions must not unlock geometry');
    await page.screenshot({path:path.join(qa,'ct-import-review.png')});
    await page.locator('#active-case').selectOption('existing');
    await page.locator('#active-case').selectOption(id);
    await review.locator('#reviewer').filter({}).waitFor();
    assert.equal(await review.locator('#reviewer').inputValue(),'QA persistence test');
    await page.setViewportSize({width:390,height:844});
    await page.locator('[data-step=import]').click();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1),'Mobile upload overflows');
    await page.screenshot({path:path.join(qa,'ct-import-mobile.png')});
    assert.equal(await hash(input),original,'Source CT changed'); assert.deepEqual(errors,[]);
    const report={status:'pass',case:id,input:'existing CT p1 copied through upload',actual_cpu_inference:true,generated_review_and_3d:true,pending_review_saved:true,patient_cfd_results:0,source_unchanged:true,errors};
    await fs.writeFile(path.join(qa,'ct-import-verification.json'),JSON.stringify(report,null,2)+'\n');
    console.log(JSON.stringify(report));
  } finally {await browser.close();}
})().catch(err=>{console.error(err);process.exitCode=1;});
